def load_config(config_path: str) -> dict:  # type: ignore[type-arg]
    """Load a YAML config file into a plain dict."""
    with open(config_path) as f:
        cfg: dict = yaml.safe_load(f)  # type: ignore[assignment]
    return cfg


def build_class_weight_tensor(
    class_weights_json: str,
    device: torch.device,
) -> torch.Tensor:
    """Load class weights indexed explicitly by CANONICAL_CLASSES order.

    IMPORTANT (§4.1): We never call .values() on the dict because dict
    insertion order is fragile if the JSON is regenerated by different code.
    Explicit CANONICAL_CLASSES indexing is the only safe approach.
    """
    with open(class_weights_json) as f:
        raw_weights: dict[str, float] = json.load(f)

    # Validate that the JSON contains all expected keys
    missing = set(CANONICAL_CLASSES) - set(raw_weights.keys())
    if missing:
        raise ValueError(
            f"class_weights.json is missing keys: {missing}. "
            f"Expected all of: {CANONICAL_CLASSES}"
        )

    weights = torch.tensor(
        [raw_weights[cls] for cls in CANONICAL_CLASSES],
        dtype=torch.float32,
    ).to(device)
    return weights


#: Research-protocol options and the values implemented so far. Anything else is
#: rejected loudly instead of being silently ignored (R5 extends these).
SUPPORTED_OPTIONS: dict[str, tuple] = {  # type: ignore[type-arg]
    "preprocess_mode": ALL_MODES,
    "sampler": ("none", "acquisition_balanced"),
    "style_aug": (False, True),
    "use_acam": (False,),
}


def assert_supported_options(cfg: dict) -> None:  # type: ignore[type-arg]
    defaults = {"preprocess_mode": "resize", "sampler": "none", "style_aug": False, "use_acam": False}
    for key, allowed in SUPPORTED_OPTIONS.items():
        value = cfg.get(key, defaults[key])
        if value not in allowed:
            raise NotImplementedError(f"{key}={value!r} is not implemented yet (allowed: {allowed}).")
    p = float(cfg.get("caliper_aug_p", 0.0))
    if not 0.0 <= p <= 1.0:
        raise ValueError(f"caliper_aug_p={p} outside [0, 1]")
    if p > 0 and not is_letterbox(cfg.get("preprocess_mode", "resize")):
        raise NotImplementedError("caliper_aug_p > 0 needs a letterbox preprocess_mode (native-scale sector mask).")


def assert_no_leakage(cfg: dict, test_csv: str = "data/splits/test.csv") -> None:  # type: ignore[type-arg]
    """Ground rule 1: never train or select on test/external data.

    * train_csv / val_csv paths must not contain any forbidden token
      (test, cross_device, external, african, landmark, hc18, ucl, multitask);
    * train, val and test patient sets must be pairwise disjoint.
    """
    import pandas as pd

    for key in ("train_csv", "val_csv"):
        tok = forbidden_token_in(cfg[key])
        if tok is not None:
            raise AssertionError(f"{key}={cfg[key]!r} contains forbidden token {tok!r} (test/external data)")

    patients = {
        name: set(pd.read_csv(path, usecols=["patient_id"])["patient_id"])
        for name, path in (("train", cfg["train_csv"]), ("val", cfg["val_csv"]), ("test", test_csv))
        if Path(path).exists()
    }
    names = sorted(patients)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            overlap = patients[a] & patients[b]
            if overlap:
                raise AssertionError(f"patient overlap between {a} and {b}: {len(overlap)} patients")


FROZEN_CHECKPOINT_ROOT = Path("checkpoints")


def assert_not_frozen(cfg: dict) -> None:  # type: ignore[type-arg]
    """Refuse any checkpoint_dir/log_dir inside the frozen checkpoints/ folder."""
    frozen = FROZEN_CHECKPOINT_ROOT.resolve()
    for key in ("checkpoint_dir", "log_dir"):
        target = Path(cfg.get(key, f"checkpoints/{cfg['backbone']}")).resolve()
        if frozen == target or frozen in target.parents:
            raise SystemExit(
                f"Refusing to write into frozen {FROZEN_CHECKPOINT_ROOT}/ ({key}={cfg.get(key)}). "
                "Pass --out-dir runs/<run_id>."
            )


def resolve_output_dirs(cfg: dict, out_dir: str | None) -> dict:  # type: ignore[type-arg]
    """Apply --out-dir (checkpoint + TensorBoard dirs) and check the frozen-folder rule."""
    if out_dir is not None:
        cfg["checkpoint_dir"] = str(Path(out_dir))
        cfg["log_dir"] = str(Path(out_dir) / "tb")
    assert_not_frozen(cfg)
    return cfg


def seed_worker(worker_id: int) -> None:
    """Seed numpy and random in each DataLoader worker from torch's per-worker seed."""
    s = torch.initial_seed() % 2**32
    np.random.seed(s)
    random.seed(s)


class RecordingSampler(torch.utils.data.Sampler):  # type: ignore[type-arg]
    """Wraps a sampler and keeps the indices of the latest epoch (realised-joint check)."""

    def __init__(self, inner: torch.utils.data.Sampler):  # type: ignore[type-arg]
        self.inner = inner
        self.last: list[int] = []

    def __iter__(self):
        self.last = list(iter(self.inner))
        return iter(self.last)

    def __len__(self) -> int:
        return len(self.inner)  # type: ignore[arg-type]


def git_describe() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short=10", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_env(path: Path) -> None:
    out = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True)
    path.write_text(out.stdout, encoding="utf-8")


def run_is_done(ckpt_dir: Path) -> bool:
    return (ckpt_dir / "best.pt").exists() and (ckpt_dir / "DONE").exists()


