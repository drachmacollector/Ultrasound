"""
scripts/research/e1_confounding_tables.py  (R3 E1: descriptive confounding, RQ1)

Machine / operator / image-size x class structure of FETAL_PLANES_DB, with patient-clustered
CIs for the associations and the key contrasts.

Outputs: results/json/E1.json, results/tables/E1.md, results/figures/E1_confound_mosaic.{pdf,png}
Usage:   python scripts/research/e1_confounding_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, ".")
from src.audit.plotting import CLASS_COLORS, INK, plt, save  # noqa: E402
from src.data.dataset import CANONICAL_CLASSES  # noqa: E402
from src.data.labels import COLLAPSED  # noqa: E402
from src.eval import metrics as M  # noqa: E402
from src.eval.scoring import estimate_json  # noqa: E402
from src.eval.stats import CMMetric, RatioMetric, SumsMetric, cluster_bootstrap, safe_div  # noqa: E402

META = Path("data/processed/metadata/acquisition_metadata.parquet")
OUT_JSON = Path("results/json/E1.json")
OUT_MD = Path("results/tables/E1.md")
MACHINES = ["Aloka", "Voluson E6", "Voluson S10", "Other"]
OPERATORS = ["Op. 1", "Op. 2", "Op. 3", "Other"]
# 00_INDEX §3.1 (verified 2026-11-12): (n, Other share)
EXPECTED = {"trainval": {"Aloka": (3377, 0.651), "Voluson E6": (3456, 0.136), "Voluson S10": (11, 0.0),
                         "Other": (285, 0.042)},
            "test": {"Aloka": (1737, 0.520), "Voluson E6": (2406, 0.088), "Voluson S10": (1071, 0.516),
                     "Other": (57, 0.175)}}
SIZE_BUCKET_PX = 50
MIN_BUCKET_N = 20
MIN_CI_PATIENTS = 10      # strata with fewer patients get no CI (resamples often lack them)


def load() -> pd.DataFrame:
    d = pd.read_parquet(META)
    d["part"] = np.where(d["split"] == "test", "test", "trainval")
    w = (d["width"] / SIZE_BUCKET_PX).round().astype(int) * SIZE_BUCKET_PX
    h = (d["height"] / SIZE_BUCKET_PX).round().astype(int) * SIZE_BUCKET_PX
    d["size_bucket"] = w.astype(str) + "x" + h.astype(str)
    rare = d["size_bucket"].map(d["size_bucket"].value_counts()) < MIN_BUCKET_N
    d.loc[rare, "size_bucket"] = "rare"
    d["is_other"] = (d["plane_label"] == "Other").astype(int)
    for m in MACHINES:
        k = m.replace(" ", "_")
        d[f"m_{k}"] = (d["source_machine"] == m).astype(int)
        d[f"o_{k}"] = d[f"m_{k}"] * d["is_other"]
    return d


def check_expected(d: pd.DataFrame) -> dict:
    out = {}
    for part, exp in EXPECTED.items():
        g = d[d["part"] == part].groupby("source_machine")["is_other"].agg(["size", "mean"])
        for m, (n, share) in exp.items():
            assert int(g.loc[m, "size"]) == n, (part, m, g.loc[m, "size"])
            assert round(float(g.loc[m, "mean"]), 3) == share, (part, m, g.loc[m, "mean"])
            out[f"{part}/{m}"] = {"n": n, "other_share": round(float(g.loc[m, "mean"]), 4)}
    return out


def crosstab(d: pd.DataFrame, row: str, col: str, rows: list[str], cols: list[str]) -> pd.DataFrame:
    t = pd.crosstab(d[row], d[col]).reindex(index=rows, columns=cols, fill_value=0)
    return t


def pct_table(t: pd.DataFrame) -> pd.DataFrame:
    """'n (row%)' cells plus a row total."""
    pct = t.div(t.sum(axis=1).replace(0, np.nan), axis=0)
    out = t.astype(str) + " (" + (100 * pct).round(1).astype(str) + "%)"
    out["n"] = t.sum(axis=1)
    return out


def cramers(d: pd.DataFrame, row: str, rows: list[str], col: str = "plane_label",
            cols: list[str] = CANONICAL_CLASSES):
    return cluster_bootstrap(d, CMMetric(f"cramers_v_{row}", row, col, rows, M.cramers_v, pred_classes=cols),
                             max_nan_frac=0.01)


def main() -> None:
    d = load()
    checks = check_expected(d)
    res: dict = {"checks_vs_00_index": checks, "n_images": len(d), "n_patients": int(d["patient_id"].nunique())}
    md = ["# E1: confounding structure of FETAL_PLANES_DB", "",
          "Generated by `scripts/research/e1_confounding_tables.py`. CIs: 95% patient-clustered bootstrap "
          "(B = 2000, seed 20261109). `trainval` = train + val (what the models learn from).", ""]

    # ---- associations ------------------------------------------------------------------------
    sizes = sorted(d["size_bucket"].unique())
    res["cramers_v"] = {}
    for part in ("trainval", "test", "all"):
        g = d if part == "all" else d[d["part"] == part]
        res["cramers_v"][part] = {
            "machine_x_class8": cramers(g, "source_machine", MACHINES),
            "machine_x_collapsed": cramers(g, "source_machine", MACHINES, "plane_collapsed", COLLAPSED),
            "operator_x_class8": cramers(g, "operator", OPERATORS),
            "size_bucket_x_class8": cramers(g, "size_bucket", sizes),
            "size_bucket_x_machine": cramers(g, "size_bucket", sizes, "source_machine", MACHINES),
        }
    md += ["## 1. Association with the label (bias-corrected Cramér's V)", "",
           "| association | train+val | test | all |", "|---|---|---|---|"]
    for k in res["cramers_v"]["all"]:
        md.append(f"| {k.replace('_x_', ' × ')} | " + " | ".join(res["cramers_v"][p][k].fmt()
                                                              for p in ("trainval", "test", "all")) + " |")
    md += ["", f"Image size buckets: width and height rounded to {SIZE_BUCKET_PX} px; buckets with < {MIN_BUCKET_N} "
           f"images pooled as `rare` ({len(sizes)} buckets).", ""]

    # ---- contrasts ---------------------------------------------------------------------------
    tv = d[d["part"] == "trainval"]
    te = d[d["part"] == "test"]
    diff = SumsMetric("other_share_aloka_minus_e6", ["o_Aloka", "m_Aloka", "o_Voluson_E6", "m_Voluson_E6"],
                      lambda s: safe_div(s["o_Aloka"], s["m_Aloka"]) - safe_div(s["o_Voluson_E6"], s["m_Voluson_E6"]))
    share = {part: {m: cluster_bootstrap(g, RatioMetric("other_share", f"o_{m.replace(' ', '_')}",
                                                        f"m_{m.replace(' ', '_')}"), max_nan_frac=0.01)
                    for m in MACHINES if g.loc[g["source_machine"] == m, "patient_id"].nunique() >= MIN_CI_PATIENTS}
             for part, g in (("trainval", tv), ("test", te))}
    res["other_share"] = share
    res["contrasts"] = {
        "trainval_other_share_aloka_minus_e6": cluster_bootstrap(tv, diff),
        "test_other_share_aloka_minus_e6": cluster_bootstrap(te, diff),
        "test_s10_other_share": share["test"]["Voluson S10"],
        "trainval_voluson_e6_other_share_prior": share["trainval"]["Voluson E6"],
    }
    md += ["## 2. 'Other' share by machine and the key contrasts", "",
           "| machine | train+val n | train+val Other share | test n | test Other share |", "|---|---|---|---|---|"]
    for m in MACHINES:
        ntv, nte = int((tv["source_machine"] == m).sum()), int((te["source_machine"] == m).sum())
        a = share["trainval"].get(m)
        md.append(f"| {m} | {ntv} | {a.fmt(pct=True) if a else '< 10 patients'} | {nte} | {share['test'][m].fmt(pct=True)} |")
    c = res["contrasts"]
    md += ["", f"* Train+val Other share, Aloka − Voluson E6: **{c['trainval_other_share_aloka_minus_e6'].fmt(pct=True)}** "
           "(percentage points).",
           f"* Test: {c['test_other_share_aloka_minus_e6'].fmt(pct=True)}.",
           f"* Voluson S10 (11 training images, none Other) test Other share {c['test_s10_other_share'].fmt(pct=True)} vs "
           f"the Voluson E6 training prior {c['trainval_voluson_e6_other_share_prior'].fmt(pct=True)}: the S10 test set "
           "breaks the Voluson-means-standard-plane association.", ""]

    # ---- tables ------------------------------------------------------------------------------
    tables = {
        "machine_x_class8": ("source_machine", "plane_label", MACHINES, CANONICAL_CLASSES),
        "machine_x_collapsed": ("source_machine", "plane_collapsed", MACHINES, COLLAPSED),
        "operator_x_class8": ("operator", "plane_label", OPERATORS, CANONICAL_CLASSES),
    }
    res["tables"] = {}
    for part, g in (("trainval", tv), ("test", te)):
        res["tables"][part] = {}
        for name, (r, col, rows, cols) in tables.items():
            t = crosstab(g, r, col, rows, cols)
            res["tables"][part][name] = t.to_dict(orient="index")
            md += [f"## {name.replace('_x_', ' × ')} ({part}): n (row %)", "", pct_table(t).to_markdown(), ""]
    sxm = crosstab(d, "part", "source_machine", ["trainval", "test"], MACHINES)
    res["tables"]["split_x_machine"] = sxm.to_dict(orient="index")
    md += ["## split × machine", "", sxm.to_markdown(), ""]
    mo = (d.groupby(["part", "source_machine", "operator"])["is_other"].agg(n="size", other_share="mean")
          .reset_index().query("n >= 10"))
    res["tables"]["machine_operator_other_share"] = mo.round(4).to_dict(orient="records")
    md += ["## (machine, operator) → Other share (cells with n ≥ 10)", "",
           mo.to_markdown(index=False, floatfmt=".3f"), ""]
    size = (d.assign(sz=d["width"].astype(str) + "x" + d["height"].astype(str))
            .groupby("source_machine")["sz"]
            .agg(n="size", modal_size=lambda s: s.value_counts().index[0],
                 modal_share=lambda s: s.value_counts().iloc[0] / len(s),
                 n_distinct_sizes="nunique").reindex(MACHINES))
    res["tables"]["machine_image_size"] = size.reset_index().to_dict(orient="records")
    md += ["## machine × native image size", "", size.to_markdown(floatfmt=".3f"), ""]

    OUT_JSON.write_text(json.dumps(estimate_json(res), indent=1, default=str), encoding="utf-8")
    OUT_MD.write_text("\n".join(md), encoding="utf-8")
    figure(d)
    print(f"wrote {OUT_JSON}, {OUT_MD}, results/figures/E1_confound_mosaic.pdf")


def figure(d: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 3.0))
    x, ticks, labels = 0.0, [], []
    for m in MACHINES:
        for part in ("trainval", "test"):
            g = d[(d["source_machine"] == m) & (d["part"] == part)]
            share = g["plane_collapsed"].value_counts(normalize=True).reindex(COLLAPSED, fill_value=0)
            bottom = 0.0
            for c in COLLAPSED:
                ax.bar(x, share[c], bottom=bottom, color=CLASS_COLORS[c], width=0.8, edgecolor="white", linewidth=1)
                bottom += share[c]
            ax.text(x, 1.02, f"n={len(g)}", ha="center", va="bottom", fontsize=6.5, color=INK)
            ticks.append(x)
            labels.append("train+val" if part == "trainval" else "test")
            x += 1
        ax.text(x - 1.5, -0.2, m + (" *" if m == "Voluson S10" else ""), ha="center", va="top", fontsize=8,
                fontweight="bold" if m == "Voluson S10" else "normal", transform=ax.get_xaxis_transform())
        x += 0.6
    ax.set_xticks(ticks)
    ax.set_xticklabels(labels, fontsize=6.5)
    ax.set_ylim(0, 1.1)
    ax.set_yticks([0, 0.5, 1.0])
    ax.set_yticklabels(["0", "50%", "100%"])
    ax.set_ylabel("share of images")
    handles = [plt.Rectangle((0, 0), 1, 1, color=CLASS_COLORS[c]) for c in COLLAPSED]
    ax.legend(handles, COLLAPSED, ncol=6, loc="upper center", bbox_to_anchor=(0.5, -0.27), fontsize=7)
    ax.set_title("Class mix by machine: 'Other' dominates Aloka training images; "
                 "Voluson S10 (*) is almost absent from training", loc="left", fontsize=8.5)
    save(fig, "E1_confound_mosaic")


if __name__ == "__main__":
    main()
